const roots: string[] = [];

function repository(files: Record<string, string>): string {
    const root = mkdtempSync(path.join(tmpdir(), "suwgate-comments-"));
    roots.push(root);
    execFileSync("git", ["init", "-q"], { cwd: root });
    symlinkSync(path.join(SUWGATE, "node_modules"), path.join(root, "node_modules"));
    for (const [file, text] of Object.entries(files)) {
        mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
        writeFileSync(path.join(root, file), text);
    }
    return root;
}

const config = (exceptions: GuardException[] = []): Config => ({
    profiles: ["web", "dotnet", "database"],
    directories: {},
    add: [],
    skip: [],
    exceptions,
    settings: {},
});

async function failures(root: string, exceptions: GuardException[] = []): Promise<string[]> {
    const summary = await runGuards({ root, guards: commentGuards, files: repositoryFiles(root), config: config(exceptions) });
    return summary.log
        .split("\n")
        .slice(1)
        .map((line) => line.split(": ").slice(0, 2).join(": "));
}

afterEach(() => {
    for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe("the comment guards on a repository", () => {
    it("pass on files that hold only the tool directives AGENTS.md allows", async () => {
        expect(await failures(repository(WITH_TOOL_DIRECTIVES))).toEqual([]);
    }, 30_000);

    it("fail on a comment in every kind of file, each at its line", async () => {
        expect((await failures(repository(WITH_COMMENTS))).sort()).toEqual(
            [
                "comments-hash: .gitignore:2",
                "comments-hash: justfile:1",
                "comments-hash: scripts/run.sh:2",
                "comments-hash: compose.yaml:1",
                "comments-hash: Dockerfile:2",
                "comments-hash: .editorconfig:2",
                "comments-css: src/site.css:2",
                "comments-json: knip.json:2",
                "comments-markup: Directory.Build.props:2",
                "comments-markup: index.html:1",
                "comments-sql: db/0001_init.sql:1",
                "comments-csharp: App/Clock.cs:1",
                "no-in-place-switches: App/Quiet.cs:1",
                "no-in-place-switches: src/quiet.ts:1",
            ].sort(),
        );
    }, 30_000);

    it("leave the TypeScript comment to eslint, which refuses it with the exported rule", async () => {
        const root = repository(WITH_COMMENTS);
        const [result] = await new ESLint({ cwd: root }).lintFiles(["src/main.ts"]);

        expect(result?.messages.map((message) => message.ruleId)).toEqual(["suwgate/no-comments"]);
    }, 30_000);

    it("let suwgate.yml except a file with its reason", async () => {
        const root = repository({
            ...WITH_TOOL_DIRECTIVES,
            "db/0001_init.sql": "-- generated by the dump\ncreate table note (id bigint);\n",
        });

        expect(await failures(root, [{ guard: "comments-sql", target: "db/0001_init.sql", reason: "a generated dump" }])).toEqual([]);
    }, 30_000);
});

describe("comments-eslint", () => {
    it("fails on a file the eslint config does not refuse comments in", async () => {
        const root = repository({
            ...WITH_TOOL_DIRECTIVES,
            "eslint.config.js": eslintConfig(', { files: ["src/legacy.ts"], rules: { "suwgate/no-comments": "off" } }'),
            "src/legacy.ts": "export const legacy = 1;\n",
        });

        expect(await failures(root)).toEqual(["comments-eslint: src/legacy.ts"]);
    }, 30_000);

    it("fails on a file eslint ignores", async () => {
        const root = repository({
            ...WITH_TOOL_DIRECTIVES,
            "eslint.config.js": eslintConfig(', { ignores: ["src/generated.ts"] }'),
            "src/generated.ts": "export const generated = 1;\n",
        });

        expect(await failures(root)).toEqual(["comments-eslint: src/generated.ts"]);
    }, 30_000);

    it("fails once for the directory when eslint refuses comments in none of its files", async () => {
        const root = repository({ ...WITH_TOOL_DIRECTIVES, "eslint.config.js": "export default [];\n" });

        expect(await failures(root)).toEqual(["comments-eslint: ."]);
    }, 30_000);

    it("fails when eslint cannot be loaded from the profile's directory", async () => {
        const root = repository({ ...WITH_TOOL_DIRECTIVES, "web/src/main.ts": "export const start = 1;\n" });
        const summary = await runGuards({
            root,
            guards: commentGuards,
            files: repositoryFiles(root),
            config: { ...config(), directories: { web: "web" } },
        });

        expect(summary.log).toContain(
            "comments-eslint: web: eslint cannot be loaded from web: install the packages (pnpm install) and add eslint to its devDependencies",
        );
    }, 30_000);
});
