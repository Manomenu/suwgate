import { describe, expect, it } from "vitest";

import { commentsCsharp, csharpCommentsIn } from "./csharp.ts";

const texts = (source: string) => csharpCommentsIn(source).map((comment) => comment.text);

describe("comments-csharp", () => {
    it.each([
        ["/*lang=json*/", true],
        ["// <auto-generated>", true],
        ["// </auto-generated>", true],
        ["// Why: the pool is dropped first, grate reconnects", false],
        ["// the clock", false],
        ["// var x = 1;", false],
        ["// TODO: later", false],
        ["/* a block */", false],
        ["/// <summary>x</summary>", false],
        ["/** <summary>x</summary> */", false],
        ["/*lang=json*/ // and more", false],
    ])("judges %s (allowed: %s)", (comment, allowed) => {
        expect(texts(`${comment}\nclass X;`).length === 0).toBe(allowed);
    });

    it("does not read comment signs inside strings and char literals", () => {
        const source = [
            'var a = "http://x"; var b = @"// no ""quoted"" /* no */";',
            'var c = """',
            "// no",
            '""";',
            "var d = '\"'; var e = '\\''; var f = \"\\\"// no\";",
            'var g = $"{a /* yes */} // no {{ // no }}";',
            'var h = $$"""{ "json": {{a}} } // no""";',
            'var i = $@"{b}\n// no";',
            "var j = 1; // yes",
        ].join("\n");

        expect(csharpCommentsIn(source)).toEqual([
            { line: 6, text: "/* yes */" },
            { line: 10, text: "// yes" },
        ]);
    });

    it("reads past region names and preprocessor messages", () => {
        expect(texts("#region Notes \"quoted\n#warning don't\nclass X; // yes\n#endregion")).toEqual(["// yes"]);
    });

    it("counts lines through multi-line strings and comments", () => {
        expect(csharpCommentsIn('var a = @"\n\n";\n/* one\ntwo */\nvar b = 1; // three').map((comment) => comment.line)).toEqual([4, 6]);
    });

    it("skips generated files", async () => {
        const findings = await commentsCsharp.check({
            root: "/",
            files: ["App/Model.g.cs", "App/Form.Designer.cs", "App/obj/Debug/X.cs", "App/Clock.cs"],
            profiles: ["dotnet"],
            directories: {},
            exceptions: [],
            settings: undefined,
            read: () => "// the clock\nclass Clock;",
        });

        expect(findings.map((finding) => `${finding.target}:${String(finding.line)}`)).toEqual(["App/Clock.cs:1"]);
    });
});
